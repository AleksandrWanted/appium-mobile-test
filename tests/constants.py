"""Именованные таймауты для тестов.

Голые timeout=… в тестах не хардкодятся: точечные проверки ссылаются
на константы отсюда. Константы resilience-сценариев (сплэш, фон,
холодный старт) здесь же. Базовый таймаут page objects — отдельно,
задаётся в конфиге (default_timeout) и в сторедж-файле.
"""
from __future__ import annotations

# --- запуск / сплэш ---
# Сколько секунд ждать прохождения splash-активности (best-effort: на
# эмуляторе Play Integrity не проходит, UI не появляется).
SPLASH_WAIT_TIMEOUT = 10
# Сколько секунд ждать возврата приложения в foreground после activateApp.
FOREGROUND_WAIT_TIMEOUT = 10
# Запас на холодный старт после force-stop: приложение заново рисует
# splash и стартовую вкладку (реальное устройство, Samsung S21 FE).
COLD_START_TIMEOUT = 30

# --- интервалы опроса состояния приложения ---
SPLASH_POLL_INTERVAL = 1
FOREGROUND_POLL_INTERVAL = 1
STATE_POLL_INTERVAL = 1

# --- короткие (негативные) проверки ---
# Проверка отсутствия элемента: ждать весь базовый таймаут не нужно,
# элемент либо уже есть, либо не появится.
NEGATIVE_PROBE_TIMEOUT = 2
# Ожидание появления элемента после перехода экрана внутри приложения.
PAGE_LOAD_TIMEOUT = 15
