"""Компонентные тесты выхода из профиля (логаут) MTS Optimus.

Два сценария (component/android/authorization) для версии приложения 2.17.1+:
    - «Авторизоваться -> перейти на вкладку «Профиль» -> проскроллить вниз ->
      нажать «Выйти из профиля» -> подтвердить выход в диалоге -> выход
      выполнен»;
    - «...нажать «Выйти из профиля» -> в диалоге подтверждения нажать
      «ОТМЕНА» -> выход не выполнен, пользователь остаётся авторизованным».

Логаут тестируем через UI, потому что сам выход — фича продукта: кнопка
«Выйти из профиля» живёт в самом низу прокручиваемого профиля (контент
частично Compose — UiScrollable туда недотягивает, скроллим явными
mobile: scrollGesture-свайпами), по клику приложение показывает диалог
«Вы уверены, что хотите выйти?» (кнопки «ВЫЙТИ» / «ОТМЕНА»).

Штатное поведение приложения после выхода — сразу открыть полноэкранную
SSO-форму входа («Рады видеть вас снова»), а не возвращаться на вкладку
«Профиль»: разлогиненные тесты, стартующие после UI-логаута, видят экран
входа. Возврат во фреймворке к неавторизованному профилю делает
no_reset: false — pm clear следующей сессии очищает и SSO-хвост.

После «ОТМЕНА» приложение остаётся на вкладке «Профиль» с авторизованным
состоянием: проверяем полный набор признаков сессии — карточку
пользователя, карточки подписок и кнопку «Выйти из профиля».

Авторизацию выполняет фикстура authorized_app (fast-track → ввод номера →
код из СМС, см. test_mts_id_login.py).
"""
from __future__ import annotations

import allure
import pytest

from src.pages.login_page import LoginPageLocators
from tests.constants import (
    NEGATIVE_PROBE_TIMEOUT,
    PAGE_LOAD_TIMEOUT,
)


@allure.epic("Авторизация")
@allure.feature("Выход из профиля")
@pytest.mark.android
class TestMtsIdLogout:
    """Логаут: кнопка внизу профиля, диалог подтверждения, экран входа после."""

    @allure.title("Выход из профиля -> пользователь разлогинен")
    @allure.description(
        "Сценарий component/android/authorization (приложение 2.17.1+).\n\n"
        "Шаги: авторизоваться (фикстура authorized_app); открыть вкладку "
        "«Профиль»; проскроллить вниз до кнопки «Выйти из профиля» (кнопка "
        "в самом низу, скролл явными мобильными жестами); нажать кнопку; "
        "в диалоге «Вы уверены, что хотите выйти?» нажать «ВЫЙТИ»; "
        "дождаться реакции приложения.\n\n"
        "Ожидаемый результат: выход выполнен — карточка пользователя с "
        "аватаром «Изображение МТС ID» исчезла, приложение открыло "
        "полноэкранную форму входа MTS ID (fast-track «Рады видеть вас "
        "снова»): повторный вход требуется без перезапуска приложения."
    )
    @allure.severity(allure.severity_level.CRITICAL)
    @allure.id("")
    def test_logout_from_profile(self, authorized_app):
        """Кнопка выхода + подтверждение -> разлогин, показ формы входа."""
        pages = authorized_app
        driver = pages.profile.driver

        with allure.step("Открыть вкладку «Профиль» авторизованного пользователя"):
            profile = pages.profile
            assert profile.is_user_card_visible(), (
                "Карточка пользователя не видна — пользователь не авторизован")

        with allure.step("Проверить кнопку «Выйти из профиля» внизу профиля"):
            assert profile.is_logout_visible(), (
                "Кнопка «Выйти из профиля» не найдена после доскролла")

        with allure.step("Нажать «Выйти из профиля» и подтвердить выход «ВЫЙТИ»"):
            profile.logout()

        with allure.step("Проверить, что карточка пользователя исчезла"):
            # Аватар виден только у авторизованного пользователя: после
            # выхода он обязан пропасть (даём мгновение на перерисовку)
            assert not driver.is_present(LoginPageLocators.MTS_ID_AVATAR,
                                         timeout=NEGATIVE_PROBE_TIMEOUT), (
                "Карточка пользователя осталась после выхода")

        with allure.step("Проверить, что приложение показало форму входа MTS ID"):
            # Штатное поведение: после логаута открывается полноэкранная
            # SSO-форма («Рады видеть вас снова») — повторный вход требуется
            # без перезапуска приложения
            assert driver.is_present(LoginPageLocators.SCREEN_ROOT, timeout=PAGE_LOAD_TIMEOUT), (
                "Форма входа MTS ID не открылась после выхода")

    @allure.title("Отмена выхода в диалоге -> пользователь остаётся авторизованным")
    @allure.description(
        "Сценарий component/android/authorization (приложение 2.17.1+).\n\n"
        "Шаги: авторизоваться (фикстура authorized_app); открыть вкладку "
        "«Профиль»; проскроллить вниз до кнопки «Выйти из профиля»; нажать "
        "кнопку и в диалоге «Вы уверены, что хотите выйти?» нажать «ОТМЕНА»; "
        "подняться вверх вкладки и проверить авторизованное состояние.\n\n"
        "Ожидаемый результат: выход НЕ выполнен — пользователь остаётся на "
        "вкладке «Профиль» с сохранённой сессией: карточка пользователя с "
        "аватаром «Изображение МТС ID» на месте, карточки подписок "
        "отображаются, кнопка «Выйти из профиля» снова доступна."
    )
    @allure.severity(allure.severity_level.CRITICAL)
    @allure.id("")
    def test_logout_cancel_keeps_session(self, authorized_app):
        """Кнопка выхода + «ОТМЕНА» -> сессия сохранена, сессийный UI на месте."""
        pages = authorized_app
        profile = pages.profile

        with allure.step("Открыть вкладку «Профиль» авторизованного пользователя"):
            assert profile.is_user_card_visible(), (
                "Карточка пользователя не видна — пользователь не авторизован")

        with allure.step("Открыть диалог подтверждения выхода"):
            profile.open_logout_dialog()

        with allure.step("Нажать «ОТМЕНА» в диалоге подтверждения выхода"):
            profile.cancel_logout()

        with allure.step("Проверить, что сессия сохранена — карточка пользователя на месте"):
            profile.scroll_to_top()
            assert profile.is_user_card_visible(), (
                "Карточка пользователя пропала после отмены выхода")

        with allure.step("Проверить, что карточки подписок отображаются"):
            assert profile.is_subscription_card_visible(), (
                "Карточка «Запись звонков» не видна после отмены выхода")

        with allure.step("Проверить, что кнопка «Выйти из профиля» снова доступна"):
            assert profile.is_logout_visible(), (
                "Кнопка «Выйти из профиля» не найдена после отмены выхода")
