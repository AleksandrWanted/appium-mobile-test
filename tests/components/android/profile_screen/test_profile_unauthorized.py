"""Компонентные тесты вкладки «Профиль»: неавторизованное состояние.

Сценарий (component/android/profile_screen) для версии приложения 2.17.1+:
    «Перейти на вкладку «Профиль» -> пользователь не авторизован, видны
    элементы неавторизованного состояния».

С 2.17.1 контейнер notAuthZone из разметки профиля исчез; карточка входа
стала кнопкой с content-desc «Войти в МТС Optimус», закреплённой внизу
экрана, а карточка «Подписка» заменена карточками тарифов «Запись звонков»
и «ИИ-диктофон».
"""
from __future__ import annotations

import allure
import pytest


@allure.epic("Вкладка «Профиль»")
@allure.feature("Неавторизованное состояние")
@pytest.mark.android
class TestProfileUnauthorized:
    """Профиль без авторизации: кнопка входа, карточки тарифов, нижние секции."""

    @allure.title("Профиль без авторизации -> видны кнопка входа, карточки "
                  "тарифов и кнопка «ПОДКЛЮЧИТЬ»")
    @allure.description(
        "Сценарий component/android/profile_screen (приложение 2.17.1+).\n\n"
        "Шаги: открыть вкладку «Профиль» через нижнее меню; проверить переход "
        "(выбрана вкладка «Профиль», заголовок появился); проверить карточку "
        "тарифа «Запись звонков» («Абонентам МТС», «от 0₽/мес») с кнопкой "
        "«ПОДКЛЮЧИТЬ»; проверить карточку «ИИ-диктофон» («Абонентам всех "
        "операторов»); проверить закреплённую внизу кнопку входа "
        "«ВОЙТИ В МТС OPTIMUS» (content-desc «Войти в МТС Optimus»).\n\n"
        "Ожидаемый результат: все элементы неавторизованного состояния видны "
        "и заполнены ожидаемыми текстами."
    )
    @allure.severity(allure.severity_level.CRITICAL)
    @allure.id("")
    def test_profile_unauthorized_elements(self, pages):
        """Профиль без авторизации -> элементы неавторизованного состояния видны."""
        with allure.step("Перейти на вкладку «Профиль»"):
            profile = pages.common.open_profile_tab()

        with allure.step("Проверить, что вкладка «Профиль» открылась"):
            assert profile.is_loaded(), "Экран «Профиль» не загрузился"

        with allure.step("Проверить карточку тарифа «Запись звонков»"):
            assert profile.is_subscription_card_visible(), (
                "Карточка «Запись звонков» не видна")
            assert profile.is_subscribe_button_visible(), (
                "Кнопка «ПОДКЛЮЧИТЬ» не видна")

        with allure.step("Проверить карточку «ИИ-диктофон»"):
            assert profile.is_ai_recorder_card_visible(), (
                "Карточка «ИИ-диктофон» не видна")

        with allure.step("Проверить кнопку входа «Войти в МТС Optimus»"):
            assert profile.is_login_card_visible(), (
                "Кнопка входа «Войти в МТС Optimus» не видна")
            assert profile.get_login_card_text() == "ВОЙТИ В МТС OPTIMUS", (
                "Текст кнопки входа не совпадает")
